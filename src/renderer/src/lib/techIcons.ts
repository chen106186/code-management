const ICONS = new Map(
  KEYWORDS.flatMap(([icon, ...words]) => words.map((word) => [word, icon] as const))
)

/** 只认整个名称，"Vue 后台" 这种带其他内容的不算关键词。Vue.js、vuejs、vue3 都算 Vue */
export function techIcon(name: string): TechIconData | undefined {
  const word = name.trim().toLowerCase().replace(/[\s_-]+/g, '')
  const withoutVersion = word.replace(/\d+(\.\d+)*$/, '')
  return (
    ICONS.get(word) ??
    ICONS.get(withoutVersion) ??
    ICONS.get(withoutVersion.replace(/\.?js$/, ''))
  )
}
